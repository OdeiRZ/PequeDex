    /**
     * Null when there is no reference data for this exact combination
     * (measure/sex not recognised, or age beyond the 24-month table) -
     * callers show the raw measurement without a percentile rather than
     * guessing outside the data this is actually valid for.
     */
    public static function percentile(string $measure, string $sex, float $ageInMonths, float $value): ?float
    {
        $lms = self::interpolatedLms($measure, $sex, $ageInMonths);

        if ($lms === null) {
            return null;
        }

        [$l, $m, $s] = $lms;

        $z = abs($l) < 1e-9
            ? log($value / $m) / $s
            : ((($value / $m) ** $l) - 1) / ($l * $s);

        return round(self::standardNormalCdf($z) * 100, 1);
    }

    /**
     * @return array{0: float, 1: float, 2: float}|null [L, M, S]
     */
    private static function interpolatedLms(string $measure, string $sex, float $ageInMonths): ?array
    {
        $table = self::LMS[$measure][$sex] ?? null;

        if ($table === null || $ageInMonths < 0 || $ageInMonths > 24) {
            return null;
        }

        $lowerMonth = (int) floor($ageInMonths);
        $upperMonth = (int) ceil($ageInMonths);

        $lower = $table[$lowerMonth];
        $upper = $table[$upperMonth];

        if ($lowerMonth === $upperMonth) {
            return [$lower['L'], $lower['M'], $lower['S']];
        }

        // Linear interpolation between the two nearest whole months - a
        // measurement is rarely logged on an exact month boundary.
        $fraction = $ageInMonths - $lowerMonth;
        $interpolate = fn (string $key) => $lower[$key] + ($upper[$key] - $lower[$key]) * $fraction;

        return [$interpolate('L'), $interpolate('M'), $interpolate('S')];
    }

    /**
     * Abramowitz and Stegun formula 7.1.26 - accurate to ~1.5e-7, more
     * than enough precision for a percentile shown to one decimal place.
     * PHP has no built-in erf()/normal CDF.
     */
    private static function standardNormalCdf(float $z): float
    {
        $sign = $z < 0 ? -1 : 1;
        $x = abs($z) / sqrt(2);

        $a1 = 0.254829592;
        $a2 = -0.284496736;
        $a3 = 1.421413741;
        $a4 = -1.453152027;
        $a5 = 1.061405429;
        $p = 0.3275911;

        $t = 1 / (1 + $p * $x);
        $y = 1 - ((((($a5 * $t + $a4) * $t) + $a3) * $t + $a2) * $t + $a1) * $t * exp(-$x * $x);

        return 0.5 * (1 + $sign * $y);
    }
